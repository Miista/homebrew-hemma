// A service's extra directives are picked from the repo tree, so the server re-checks what the picker would have offered:
// a hand-written file inside the repo. Anything else is refused even if someone posts it directly.
func TestExtraDirectives_CheckState(t *testing.T) {
	dir := t.TempDir()
	yaml := "hosts:\n    edge:\n        ip: 192.0.2.50\ndomains:\n    - example.com\ndefaults:\n    dns_host: edge\n" +
		"services:\n    web:\n        fqdn: web.example.com\n        host: edge\n        backend: web:80\n"
	for rel, body := range map[string]string{
		"services.yaml":             yaml,
		"extras/web.caddy":          "encode gzip\n",
		"edge/caddy/data/gen.caddy": "# GENERATED by hemma — do not edit\n",
	} {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	s := &server{repo: dir}
	for _, c := range []struct {
		name string
		val  string
		err  string // "" = must pass
	}{
		{"a hand-written file in the repo", "extras/web.caddy", ""},
		{"empty clears it", "", ""},
		{"a file that does not exist", "extras/missing.caddy", "there is no"},
		{"a folder", "extras", "there is no file"},
		{"a file hemma generates", "edge/caddy/data/gen.caddy", "generated by hemma"},
		{"a path climbing out of the repo", "../outside.caddy", "not a path inside the repo"},
		{"an absolute path", "/etc/hosts", "not a path inside the repo"},
	} {
		err := s.checkState(lookup("update service"), map[string]any{"name": "web", "extra-directives": c.val})
		if c.err == "" && err != nil || c.err != "" && (err == nil || !strings.Contains(err.Error(), c.err)) {
			t.Errorf("%s (%q): err = %v, want %q", c.name, c.val, err, c.err)
		}
	}
	// the same field on add service
	if err := s.checkState(lookup("add service"), map[string]any{"name": "n", "fqdn": "n.example.com", "host": "edge", "backend": "n:1", "extra-directives": "extras/missing.caddy"}); err == nil {
		t.Error("add service must refuse a file that does not exist")
	}
}

// The form sends the picked path as --extra-directives, and an update sends an empty value too, because that is how the
// kernel is told to clear it. A request that does not carry the field (the Access page's role toggle) must not clear it.
func TestExtraDirectives_Build(t *testing.T) {
	has := func(argv []string, want string) bool {
		for _, a := range argv {
			if a == want {
				return true
			}
		}
		return false
	}
	up := lookup("update service")
	argv, err := up.build(map[string]any{"name": "web", "extra-directives": "extras/web.caddy"})
	if err != nil || !has(argv, "--extra-directives=extras/web.caddy") {
		t.Errorf("update with a file: argv = %v, err = %v", argv, err)
	}
	argv, err = up.build(map[string]any{"name": "web", "extra-directives": ""})
	if err != nil || !has(argv, "--extra-directives=") {
		t.Errorf("update with an empty value must send it (it clears): argv = %v, err = %v", argv, err)
	}
	argv, err = up.build(map[string]any{"name": "web", "auth-groups": "admins"})
	if err != nil {
		t.Fatal(err)
	}
	for _, a := range argv {
		if strings.HasPrefix(a, "--extra-directives") {
			t.Errorf("a request without the field must not touch it: %v", argv)
		}
	}
	argv, err = lookup("add service").build(map[string]any{"name": "n", "fqdn": "n.example.com", "host": "edge", "backend": "n:1", "extra-directives": ""})
	if err != nil {
		t.Fatal(err)
	}
	for _, a := range argv {
		if strings.HasPrefix(a, "--extra-directives") {
			t.Errorf("an empty value on add sends nothing: %v", argv)
		}
	}
	if strings.ContainsAny("extras/a\nb.caddy", "\n") {
		if _, err := up.build(map[string]any{"name": "web", "extra-directives": "extras/a\nb.caddy"}); err == nil {
			t.Error("a newline in the path must be refused")
		}
	}
}

// Changing the file shows up in the unsaved-changes list and in history, under its own label.
func TestExtraDirectives_InTheDiff(t *testing.T) {
	before := serviceKV(config.Service{FQDN: "web.example.com", Host: "edge", Backend: "web:80"})
	after := serviceKV(config.Service{FQDN: "web.example.com", Host: "edge", Backend: "web:80", ExtraDirectives: "extras/web.caddy"})
	if len(before) != len(after) {
		t.Fatalf("the two lists must line up: %d vs %d", len(before), len(after))
	}
	changes := compare(before, after, "changed")
	if len(changes) != 1 || changes[0].Field != "Extra directives" || changes[0].After != "extras/web.caddy" {
		t.Errorf("changes = %+v, want exactly the Extra directives field", changes)
	}
}
